//! Биндинги Ice для Murmur (Mumble server), сгенерированные из `MumbleServer.ice`.
//!
//! Крейт содержит **только** машинный вывод — рукописного кода здесь нет.
//! Человеческий API живёт слоем выше; здесь лежат сырые `*Prx`, `*I`, `*Server`
//! и Slice-типы.
//!
//! # Почему вывод закоммичен
//!
//! Раньше код генерировался в `build.rs` при каждой сборке и лежал в
//! `.gitignore`. Это требовало `rustfmt` на `PATH` у каждого потребителя, делало
//! сборку зависимой от разбора `.ice`, а изменения биндингов были невидимы в
//! ревью. Теперь вывод в git, а генерация — осознанный ручной шаг.
//!
//! # Регенерация
//!
//! ```sh
//! cargo run -p ice-rs --bin slice2rs -- \
//!     crates/murmur-slice/src/gen \
//!     crates/murmur-slice/MumbleServer.ice \
//!     -i crates/murmur-slice/include
//! ```
//!
//! После этого посмотреть диффы и закоммитить. CI проверяет, что регенерация не
//! даёт расхождений с закоммиченным.

pub mod gen;

/// Всё, что обычно нужно: типы Murmur и его интерфейсы.
pub use gen::mumble_server;
